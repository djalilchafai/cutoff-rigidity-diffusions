#!/usr/bin/env python3
"""Generate the reduced Palomar pair from the full statement surface.

PalomarChallenge.lean keeps, verbatim, the theorems listed in CORE below and the
definitions of Challenge.lean they depend on (transitive closure, computed on the
code without docstrings), together with the structural lines (`section`, `open`,
`variable`, `end`). PalomarSolution.lean keeps the same theorems of Solution.lean
(generated by gen-solution.py). comparator-palomar.json lists them. Every kept
declaration is a verbatim copy of the full Challenge, so the definitions are those
of CutoffRigidity/Statements.lean, which the proofs use.

Run after gen-solution.py whenever Challenge.lean changes.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent

# The main results of the paper, the link between the kernel and the SDE, and the
# non-vacuity of the two standing Euclidean hypotheses.
CORE = [
    "exists_euclideanLangevin_of_convex",
    "euclideanDiffusion_unique_of_convex",
    "exists_langevin",
    "isLangevinSolution_map_eq_kernel_of_convex",
    "main_wasserstein_estimate",
    "eigenspace_dim_and_lambda",
    "wasserstein_cutoff",
    "information_cutoff",
    "lp_cutoff",
    "convex_interaction",
    "convex_interaction_cutoff",
    "product_condition_cutoff",
    "euclidean_gaussian_factorization",
    "eigenmap_is_ou",
    "riemannian_wasserstein_estimate",
    "riemannian_gaussian_splitting",
]

HEADER_DOC = """/-!
# Cutoff via rigidity for high dimensional curved diffusions: main results

Generated from `Challenge.lean` by `scripts/gen-palomar.py`. D. Chafaï and M. Fathi, CRAS 363 (2025)
1103–1121, corrected version arXiv:2412.15969v5. Statements: Theorems 1.1, 1.5, 1.7, 1.9, 3.1, 3.6,
Lemma 3.3, Remark 1.2, Corollaries 1.3, 1.4, 1.6, display (1.25); for convex potentials, existence and
uniqueness of the kernel and its identification with the law of the SDE (1.1). Definitions use Mathlib
only; deviations from v5 are flagged in the docstrings. Full surface (69 statements): `Challenge.lean`.
"""

DECL = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+|private\s+|protected\s+)*(theorem|def|abbrev|structure)\s+([^\s({\[:]+)", re.M)
IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_'.]*")
DOC = re.compile(r"/--.*?-/", re.S)


def split(path):
    text = (ROOT / path).read_text(encoding="utf-8")
    marker = "namespace CutCur\n"
    head, body = text.split(marker, 1)
    blocks = []
    paras, acc = [], ""
    for para in re.split(r"\n\s*\n", body):
        acc = para if not acc else acc + "\n\n" + para
        if acc.count("/-") <= acc.count("-/"):  # comments may contain blank lines
            paras.append(acc)
            acc = ""
    assert not acc, f"{path}: unterminated comment"
    for para in paras:
        if not para.strip():
            continue
        decls = DECL.findall(para)
        assert len(decls) <= 1, f"{path}: several declarations in one paragraph:\n{para[:300]}"
        kind, name = decls[0] if decls else ("other", None)
        blocks.append((kind, name, para.strip("\n")))
    return head + marker, blocks


def tokens(text):
    return set(IDENT.findall(DOC.sub("", text)))


def select(blocks, defs_kept):
    out = []
    for kind, name, para in blocks:
        if kind == "theorem" and name in CORE:
            out.append(para)
        elif kind in ("def", "abbrev", "structure") and name in defs_kept:
            out.append(para)
        elif kind == "other" and not para.lstrip().startswith("/-!"):
            out.append(para)  # section / open / variable / end
    return out


def main():
    chead, cblocks = split("Challenge.lean")
    names = [n for k, n, _ in cblocks if k == "theorem"]
    missing = [n for n in CORE if n not in names]
    assert not missing, f"not in Challenge.lean: {missing}"
    defs = {n: p for k, n, p in cblocks if k in ("def", "abbrev", "structure")}
    kept, frontier = set(), set()
    for k, n, p in cblocks:
        if k == "theorem" and n in CORE:
            frontier |= tokens(p)
    while True:
        new = {d for d in defs if d not in kept and (d in frontier or f"CutCur.{d}" in frontier)}
        if not new:
            break
        kept |= new
        for d in new:
            frontier |= tokens(defs[d])
    chead = re.sub(r"/-!.*?-/\n", HEADER_DOC.rstrip("\n") + " -/\n", chead, count=1, flags=re.S)
    challenge = chead + "\n" + "\n\n".join(select(cblocks, kept)) + "\n"
    (ROOT / "PalomarChallenge.lean").write_text(challenge, encoding="utf-8")

    shead, sblocks = split("Solution.lean")
    sdoc = HEADER_DOC.replace("Generated from `Challenge.lean` by `scripts/gen-palomar.py`.",
                              "Proofs, generated from `Solution.lean` by `scripts/gen-palomar.py`.")
    shead = re.sub(r"/-!.*?-/\n", sdoc.rstrip("\n") + " -/\n", shead, count=1, flags=re.S)
    solution = shead + "\n" + "\n\n".join(select(sblocks, set())) + "\n"
    (ROOT / "PalomarSolution.lean").write_text(solution, encoding="utf-8")

    full = json.loads((ROOT / "comparator.json").read_text(encoding="utf-8"))
    config = {
        "challenge_module": "PalomarChallenge",
        "solution_module": "PalomarSolution",
        "theorem_names": [f"CutCur.{n}" for n in names if n in CORE],
        "definition_names": [d for d in full["definition_names"] if d.removeprefix("CutCur.") in kept],
        "permitted_axioms": full["permitted_axioms"],
    }
    for key, value in full.items():
        config.setdefault(key, value)
    (ROOT / "comparator-palomar.json").write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"PalomarChallenge.lean: {challenge.count(chr(10))} lines, {len(challenge.encode())} bytes, "
          f"{len(config['theorem_names'])} theorems, {len(kept)} definitions kept")


if __name__ == "__main__":
    main()
