#!/usr/bin/env python3
"""Generate CutoffRigidity/Statements.lean: the Challenge definitions without theorems.

Solution.lean imports this module, so every definition compared by Comparator is
elaborated from exactly the same source text as in Challenge.lean.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "Challenge.lean").read_text(encoding="utf-8")
# Drop each theorem together with its docstring; Challenge theorems end with `  sorry`.
lines = src.split("\n")
keep = []
i = 0
while i < len(lines):
    if lines[i].startswith("theorem "):
        if keep and keep[-1].rstrip().endswith("-/"):
            while keep and not keep.pop().startswith("/--"):
                pass
        while lines[i] != "  sorry":
            i += 1
        i += 1
        if i < len(lines) and lines[i] == "":
            i += 1
        continue
    keep.append(lines[i])
    i += 1
out = "\n".join(keep)
if "\ntheorem " in out or "sorry" in out:
    sys.exit("could not strip every Challenge theorem")
out = out.replace("# Cutoff via rigidity for high-dimensional curved diffusions: statements",
                  "# Definitions of the Challenge statement surface (generated)", 1)
out = out.replace("module\n", "module\n\n-- Generated by scripts/sync-statements.py from Challenge.lean; do not edit.\n", 1)
target = ROOT / "CutoffRigidity" / "Statements.lean"
if "--check" in sys.argv:
    sys.exit(0 if target.read_text(encoding="utf-8") == out else "Statements.lean is out of date")
target.write_text(out, encoding="utf-8")
